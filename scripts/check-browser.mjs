import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:390,height:844},permissions:['geolocation'],geolocation:{latitude:12.9716,longitude:77.5946,accuracy:10}});
const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:5173');
await page.getByText('Live location · ±10 m').waitFor();
await page.getByRole('button',{name:'Save parking',exact:false}).click();
await page.getByText('Your parking spot',{exact:true}).waitFor();
await page.reload();await page.getByText('Your parking spot',{exact:true}).waitFor();
await context.setGeolocation({latitude:12.975,longitude:77.596,accuracy:10});
await page.getByRole('button',{name:'Walk to my car',exact:false}).click();
await page.getByText('Follow the green walking route back to your car.').waitFor({timeout:30000});
await page.getByRole('button',{name:'Settings',exact:true}).click();
await page.getByLabel('Mapbox public access token').fill('bad-token');await page.getByRole('button',{name:'Connect map',exact:false}).click();
await page.getByText('Please use a public token starting with pk.').waitFor();
await page.getByRole('button',{name:'Close settings'}).click();
page.on('dialog',d=>d.accept());await page.getByRole('button',{name:'End parking'}).click();
await page.getByRole('button',{name:'Save parking',exact:false}).waitFor();
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await page.screenshot({path:'/tmp/parkpin-mobile.png'});
await page.setViewportSize({width:1440,height:900});await page.screenshot({path:'/tmp/parkpin-desktop.png'});
assert.deepEqual(errors,[]);
await context.close();
const denied=await browser.newContext({viewport:{width:390,height:844}});const p=await denied.newPage();await p.goto('http://localhost:5173');await p.getByText('Location unavailable',{exact:true}).waitFor();await p.getByRole('button',{name:'Save parking',exact:false}).click();assert.equal(await p.getByText('Your parking spot',{exact:true}).isVisible(),false);await denied.close();
await browser.close();console.log('PASS: mobile GPS save, persistence, movement, token validation, clear, layout, desktop render, permission denied; no page errors. Mapbox route response verified with simulated GPS.');
